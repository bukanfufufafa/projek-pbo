    public void tampildata() {
        //        membuat header table
        Object header[] = {"id", "Recipe Name", "Ingredients"};
        DefaultTableModel data = new DefaultTableModel(null, header);
        tableData.setModel(data);

//          Query
        String queryTampil = "SELECT * FROM resep_burger";
        try {
//            mengirimkan query
            Statement st = kon.con.createStatement();
//            menyimpan hasil sementara dari database
            ResultSet rs = st.executeQuery(queryTampil);
//            memasukkan data ke tabel
            while (rs.next()) {
                String kolom1 = rs.getString(1);
                String kolom2 = rs.getString(2);
                String kolom3 = rs.getString(3);
                String kolom[] = {kolom1, kolom2, kolom3};

                data.addRow(kolom);
            }
        } catch (Exception e) {
            System.out.println(e.getMessage());
        }
    }

    public void loadBahan() {
        try {
            // Kosongkan isi combobox terlebih dahulu agar tidak duplikat
            cmbBahan.removeAllItems();
            cmbBahan.addItem("- Pilih Bahan -"); // Placeholder opsional

            // Query untuk mengambil data bahan
            String queryBahan = "SELECT nama_bahan FROM bahan ORDER BY nama_bahan ASC";

            // Mengirimkan query menggunakan koneksi 'kon.con' milik Anda
            Statement st = kon.con.createStatement();

            // Menyimpan hasil dari database
            ResultSet rs = st.executeQuery(queryBahan);

            // Memasukkan data nama bahan satu per satu ke combobox
            while (rs.next()) {
                String namaBahan = rs.getString("nama_bahan");
                cmbBahan.addItem(namaBahan);
            }
        } catch (Exception e) {
            // Menampilkan error jika ada masalah
            System.out.println("Error loadBahan: " + e.getMessage());
        }
    }
