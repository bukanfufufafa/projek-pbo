    private void btnTambahBahanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnTambahBahanMouseClicked
        String bahanPilihan = cmbBahan.getSelectedItem().toString();
        String SusunanBahan = taSusunanBahan.getText();

        if (bahanPilihan.equals("- Pilih Bahan -")) {
            JOptionPane.showMessageDialog(this, "Silakan pilih bahan terlebih dahulu!");
            return;
        }

        if (SusunanBahan.isEmpty()) {
            taSusunanBahan.setText(bahanPilihan);
        } else {
            taSusunanBahan.setText(SusunanBahan + "," + bahanPilihan);
        }
    }//GEN-LAST:event_btnTambahBahanMouseClicked

    private void btnSimpanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnSimpanMouseClicked
        String namaResep = txtNamaResep.getText();
        String susunanBahan = taSusunanBahan.getText();

        if (namaResep.isEmpty() || susunanBahan.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Nama resep dan susunan bahan tidak boleh kosong!");
            return;
        }

        String querySimpan = "INSERT INTO resep_burger (nama_resep, urutan_bahan) VALUES ('" + namaResep + "', '" + susunanBahan + "')";

        try {
            Statement st = kon.con.createStatement();
            st.executeUpdate(querySimpan);
            JOptionPane.showMessageDialog(null, "Data " + namaResep + " berhasil ditambahkan");

            tampildata();

            txtNamaResep.setText("");
            taSusunanBahan.setText("");

            if (cmbBahan.getItemCount() > 0) {
                cmbBahan.setSelectedIndex(0);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan resep: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanMouseClicked

    private void btnHapusBahanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnHapusBahanMouseClicked
        String susunanBahan = taSusunanBahan.getText();

        if (susunanBahan.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Susunan bahan sudah kosong!");
            return;
        }

        int komaTerakhir = susunanBahan.lastIndexOf(",");

        if (komaTerakhir == -1) {
            taSusunanBahan.setText("");
        } else {
            String teksBaru = susunanBahan.substring(0, komaTerakhir);
            taSusunanBahan.setText(teksBaru);
        }
    }//GEN-LAST:event_btnHapusBahanMouseClicked

    private String idResepTerpilih;
    private void tableDataMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableDataMouseClicked
        // Mendapatkan indeks baris yang diklik
        int baris = tableData.getSelectedRow();

        // Memastikan ada baris yang valid (tidak error)
        if (baris != -1) {
            // Mengambil data dari JTable
            // Asumsi: indeks 0 = id, 1 = Nama Resep, 2 = Urutan Bahan
            idResepTerpilih = tableData.getValueAt(baris, 0).toString();
            String namaResep = tableData.getValueAt(baris, 1).toString();
            String susunanBahan = tableData.getValueAt(baris, 2).toString();

            // Memasukkan data ke TextField dan TextArea
            txtNamaResep.setText(namaResep);
            taSusunanBahan.setText(susunanBahan);
        }
    }//GEN-LAST:event_tableDataMouseClicked

    private void btnUpdateMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnUpdateMouseClicked
        String namaResepBaru = txtNamaResep.getText();
        String susunanBahanBaru = taSusunanBahan.getText();

        if (idResepTerpilih.equals("")) {
            JOptionPane.showMessageDialog(null, "Silakan pilih data dari tabel terlebih dahulu!");
            return;
        }

        if (namaResepBaru.isEmpty() || susunanBahanBaru.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Nama resep dan susunan bahan tidak boleh kosong!");
            return;
        }

        String queryUpdate = "UPDATE resep_burger SET nama_resep = '" + namaResepBaru
                + "', urutan_bahan = '" + susunanBahanBaru
                + "' WHERE id = '" + idResepTerpilih + "'";

        try {
            Statement st = kon.con.createStatement();
            st.executeUpdate(queryUpdate);
            JOptionPane.showMessageDialog(null, "Data resep berhasil diperbarui!");

            tampildata();

            txtNamaResep.setText("");
            taSusunanBahan.setText("");
            idResepTerpilih = "";

        } catch (Exception e) {
            System.out.println("Error saat update: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateMouseClicked

    private void btnHapusMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnHapusMouseClicked
        if (idResepTerpilih.equals("")) {
            JOptionPane.showMessageDialog(null, "Silakan pilih data dari tabel yang ingin dihapus terlebih dahulu!");
            return;
        }

        // munculkan dialog konfirmasi sebelum menghapus
        int konfirmasi = JOptionPane.showConfirmDialog(null,
            "Apakah Anda yakin ingin menghapus resep ini?",
            "Konfirmasi Hapus",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE);

        // mengecek pilihan user
        if (konfirmasi == JOptionPane.YES_OPTION) {

            String queryHapus = "DELETE FROM resep_burger WHERE id = '" + idResepTerpilih + "'";

            try {
                Statement st = kon.con.createStatement();
                st.executeUpdate(queryHapus);

                JOptionPane.showMessageDialog(null, "Data resep berhasil dihapus!");

                tampildata();

                txtNamaResep.setText("");
                taSusunanBahan.setText("");
                idResepTerpilih = "";

                if (cmbBahan.getItemCount() > 0) {
                    cmbBahan.setSelectedIndex(0);
                }

            } catch (Exception e) {
                System.out.println("Error saat menghapus data: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusMouseClicked

