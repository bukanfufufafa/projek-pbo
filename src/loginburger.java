    private void btnHapusAkunActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusAkunActionPerformed
        String username = txtUsername.getText();

        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Isi username yang ingin dihapus!");
            return;
        }

        int konfirmasi = JOptionPane.showConfirmDialog(
                this,
                "Yakin ingin menghapus akun ini?",
                "Konfirmasi",
                JOptionPane.YES_NO_OPTION
        );

        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                Connection conn = db.getConnection();

                String sql = "DELETE FROM akun WHERE username = ?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, username);

                int hasil = pst.executeUpdate();

                if (hasil > 0) {
                    JOptionPane.showMessageDialog(this, "Akun berhasil dihapus!");
                    txtUsername.setText("");
                    txtPassword.setText("");
                } else {
                    JOptionPane.showMessageDialog(this, "Username tidak ditemukan!");
                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus akun: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusAkunActionPerformed

