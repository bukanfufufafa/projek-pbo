    private void btnDaftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDaftarActionPerformed
        String username = txtUsername.getText();
        String password = new String(txtPassword.getPassword());

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Isi username dan password terlebih dahulu!");
            return;
        }

        try {
            Connection conn = db.getConnection();

            String sql = "INSERT INTO akun (username, password) VALUES (?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, username);
            pst.setString(2, password);

            pst.executeUpdate();

            PreparedStatement getId =
                conn.prepareStatement(
                    "SELECT id FROM akun WHERE username = ?"
                );

            getId.setString(1, username);

            ResultSet rsId = getId.executeQuery();

            if(rsId.next()){

                int idAkun = rsId.getInt("id");

                PreparedStatement stat =
                    conn.prepareStatement(
                        "INSERT INTO player_stats "
                    + "(id_akun, jumlah_burger_dibuat, skor, koin) "
                    + "VALUES (?,0,0,0)"
                    );

                stat.setInt(1, idAkun);
                stat.executeUpdate();
            }

            JOptionPane.showMessageDialog(this, "Akun berhasil didaftarkan!");

            txtUsername.setText("");
            txtPassword.setText("");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal daftar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDaftarActionPerformed

    private void btnUbahPasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahPasswordActionPerformed
        String username = txtUsername.getText();
        String passwordBaru = new String(txtPassword.getPassword());

        if (username.isEmpty() || passwordBaru.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Isi username dan password baru!");
            return;
        }

        try {
            Connection conn = db.getConnection();

            String sql = "UPDATE akun SET password = ? WHERE username = ?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, passwordBaru);
            pst.setString(2, username);

            int hasil = pst.executeUpdate();

            if (hasil > 0) {
                JOptionPane.showMessageDialog(this, "Password berhasil diubah!");
                txtUsername.setText("");
                txtPassword.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Username tidak ditemukan!");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mengubah password: " + e.getMessage());
        }

    }//GEN-LAST:event_btnUbahPasswordActionPerformed

